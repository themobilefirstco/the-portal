import test from 'node:test';
import http from 'node:http';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {setTimeout as delay} from 'node:timers/promises';

test('local API protects credentials, rejects cross-site writes, and persists pause',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'portal-http-'));
  const port=4380,base=`http://127.0.0.1:${port}`;
  const child=spawn(process.execPath,['src/server.mjs'],{env:{...process.env,PORTAL_DATA_DIR:dir,PORTAL_PORT:String(port),PORTAL_NO_BROWSER:'1',PORTAL_TEST_MODE:'1'},stdio:'ignore'});
  t.after(async()=>{child.kill('SIGTERM');await delay(300);fs.rmSync(dir,{recursive:true,force:true});});
  let up=false;for(let i=0;i<50;i++){try{up=(await fetch(`${base}/health`)).ok;if(up)break;}catch{}await delay(100);}assert.equal(up,true);
  const key=JSON.parse(fs.readFileSync(path.join(dir,'control-key.json'),'utf8'));
  assert.equal((await fetch(`${base}/api/status`)).status,401);
  const headers={'Content-Type':'application/json','x-room-token':key};
  const initial=await (await fetch(`${base}/api/status`,{headers})).json();
  assert.equal(initial.settings.paused,true);
  const room=await fetch(`${base}/api/room`,{method:'POST',headers,body:JSON.stringify({roomName:'Test Room',roomEmail:'new-room@example.com',timeZone:'Europe/Paris'})});
  assert.equal(room.status,200,await room.clone().text());
  const configured=await (await fetch(`${base}/api/status`,{headers})).json();
  assert.equal(configured.email,'new-room@example.com');
  assert.equal(configured.settings.timeZone,'Europe/Paris');
  assert.equal(configured.settings.paused,true);
  for(const body of ['null','[]','"text"','{']) {
    assert.equal((await fetch(`${base}/api/settings`,{method:'POST',headers,body})).status,400);
  }
  assert.equal((await fetch(`${base}/api/settings`,{method:'POST',headers,body:JSON.stringify({dashboard:'x'.repeat(100001)})})).status,413);
  assert.equal((await fetch(`${base}/api/settings`,{method:'POST',headers:{...headers,'Content-Type':'application/json-fake'},body:'{}'})).status,405);
  const reboundStatus=await new Promise((resolve,reject)=>{const r=http.get(`${base}/api/status`,{headers:{...headers,Host:'evil.example'}},res=>{res.resume();resolve(res.statusCode);});r.on('error',reject);});
  assert.equal(reboundStatus,403);
  assert.equal((await fetch(`${base}/api/connect`,{method:'POST',headers,body:'{}'})).status,400);
  const setupRequest=body=>fetch(`${base}/api/setup`,{method:'POST',headers,body:JSON.stringify(body)});
  assert.equal((await setupRequest({devicesConfirmed:true})).status,400);
  assert.equal((await setupRequest({brandedUrl:'https://meet.example.com/miami'})).status,400);
  assert.equal((await setupRequest({completed:true})).status,400);
  assert.equal((await fetch(`${base}/api/setup/finish`,{method:'POST',headers,body:'{"visitConfirmed":true}'})).status,400);
  assert.equal((await (await fetch(`${base}/api/status`,{headers})).json()).settings.paused,true);
  assert.equal((await fetch(`${base}/setup.js`)).status,200);
  const attack=await fetch(`${base}/api/settings`,{method:'POST',headers:{...headers,Origin:'https://evil.example'},body:'{"paused":true}'});assert.equal(attack.status,403);
  const response=await fetch(`${base}/api/settings`,{method:'POST',headers,body:'{"paused":true}'});const s=await response.json();assert.equal(response.status,200,JSON.stringify(s));assert.equal(s.settings.paused,true);assert.equal(s.camera,'on');assert.equal(s.microphone,'on');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'settings.json'),'utf8')).paused,true);
  assert.equal(JSON.stringify(s).includes(key),false);
  const html=await (await fetch(base)).text();assert.ok(html.includes('The Portal'));assert.equal(html.includes(key),false);
  const bad=await fetch(`${base}/api/settings`,{method:'POST',headers,body:'{"dashboard":"javascript:alert(1)"}'});assert.equal(bad.status,400);
  assert.equal(s.settings.aloneLeaveSeconds,60);
  assert.equal(s.settings.dropInEnabled,false);
  const roomUrl = 'https://meet.google.com/abc-defg-hij';
  const configure = body => fetch(`${base}/api/drop-in`, {method: 'POST', headers, body: JSON.stringify(body)});
  assert.equal((await configure({enabled: false, url: roomUrl})).status,200);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'settings.json'),'utf8')).dropInUrl,roomUrl);
  assert.equal((await configure({enabled: true, url: roomUrl})).status,400);
  assert.equal((await configure({enabled: true, url: roomUrl, accessConfirmed: true})).status,400);
  assert.equal((await configure({enabled: false, url: 'https://evil.example'})).status,400);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'settings.json'),'utf8')).dropInEnabled,false);
  const departure=await fetch(`${base}/api/settings`,{method:'POST',headers,body:'{"aloneLeaveSeconds":30}'});assert.equal(departure.status,200);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'settings.json'),'utf8')).aloneLeaveSeconds,30);
  for(const value of [-1,1,60000,'60',null]) {
    const invalid=await fetch(`${base}/api/settings`,{method:'POST',headers,body:JSON.stringify({aloneLeaveSeconds:value})});assert.equal(invalid.status,400);
  }
  const agentBase=`http://127.0.0.1:${port+1}`;
  assert.equal((await fetch(agentBase+'/v1/status')).status,401);
  assert.equal((await fetch(`${base}/api/agent-access`,{method:'POST',headers,body:'{"enabled":true}'})).status,200);
  const agentToken=(await (await fetch(`${base}/api/agent-token`,{method:'POST',headers,body:'{}'})).json()).token;
  assert.ok(agentToken.length>=40); assert.notEqual(agentToken,key);
  const agentHeaders={Authorization:`Bearer ${agentToken}`};
  const remoteStatus=await (await fetch(agentBase+'/v1/status',{headers:agentHeaders})).json();
  assert.equal(remoteStatus.health.healthy,false); assert.ok(remoteStatus.health.issues.includes('calendar_disconnected'));
  assert.equal((await fetch(agentBase+'/v1/health',{headers:agentHeaders})).status,503);
  const normalStatus=await (await fetch(`${base}/api/status`,{headers})).json();
  assert.equal(JSON.stringify(normalStatus).includes(agentToken),false);
  const newToken=(await (await fetch(`${base}/api/agent-token`,{method:'POST',headers,body:'{"rotate":true}'})).json()).token;
  assert.notEqual(newToken,agentToken);
  assert.equal((await fetch(agentBase+'/v1/status',{headers:agentHeaders})).status,401);
  await fetch(`${base}/api/agent-access`,{method:'POST',headers,body:'{"enabled":false}'});
  assert.equal((await fetch(agentBase+'/v1/status',{headers:{Authorization:`Bearer ${newToken}`}})).status,401);
});
